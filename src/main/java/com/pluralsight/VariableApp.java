package com.pluralsight;

public class VariableApp {
    public static void main(String[] args) {
        // Step 1
        String favoriteColor = "Green";
        int classStart = 2026;
        char middleInitial = 'R';
        boolean hasPets = true;
        String message = "You are beautiful.";

        System.out.println("My favorite color is: " + favoriteColor);
        System.out.println("I started this class in: " + classStart);
        System.out.println("My middle initial is: " + middleInitial);
        System.out.println("I have pets: " + hasPets);
        System.out.println(message);

        // Step 2
        int daysInAWeek = 7;
        double priceOfCoffee = 4.99;
        char favoriteLetter = 'B';
        boolean isRaining = true;

        System.out.println("There are " + daysInAWeek + " days in a week.");
        System.out.println("Your coffee is going to cost you: " + priceOfCoffee);
        System.out.println("My favorite letter is: "+ favoriteLetter);
        System.out.println("It is raining: " + isRaining);
    }
}
